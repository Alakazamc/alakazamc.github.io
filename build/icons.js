// ---- 渲染：run-length 合并成 <rect>，输出 <symbol> ----
function validate() {
  const errs = [];
  for (const [name, rows] of Object.entries(ICONS)) {
    if (rows.length > SIZE) errs.push(`${name}: 行数 ${rows.length} > ${SIZE}`);
    rows.forEach((r, i) => {
      if (r.length > SIZE) errs.push(`${name} 第 ${i + 1} 行超长: ${r.length} > ${SIZE}  "${r}"`);
      for (const ch of r) {
        if (ch !== '.' && !PAL[ch]) errs.push(`${name} 第 ${i + 1} 行未知字符 '${ch}'`);
      }
    });
  }
  return errs;
}

function toSymbol(name, rows) {
  const out = [];
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y].padEnd(SIZE, '.');
    let x = 0;
    while (x < SIZE) {
      const ch = row[x];
      if (ch === '.') { x++; continue; }
      let run = 1;
      while (x + run < SIZE && row[x + run] === ch) run++;
      out.push(`<rect x="${x}" y="${y}" width="${run}" height="1" fill="${PAL[ch]}"/>`);
      x += run;
    }
  }
  return `<symbol id="px-${name}" viewBox="0 0 ${SIZE} ${SIZE}">${out.join('')}</symbol>`;
}

function buildSprite() {
  const syms = Object.keys(ICONS).map((k) => toSymbol(k, ICONS[k])).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">${syms}</svg>`;
}

module.exports = { ICONS, PAL, SIZE, validate, buildSprite, toSymbol };
